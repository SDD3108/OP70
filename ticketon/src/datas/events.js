export const dates = [...new Set(events.map((event) => event.date))].sort();

export const filterEvents = ({ search = "", category = "", city = "", date = "" } = {}) => {
  const query = search.trim().toLowerCase();
  return events.filter((event) => {
    return (!query || `${event.title} ${event.category} ${event.city} ${event.venue}`.toLowerCase().includes(query)) && (!category || event.category == category) && (!city || event.city == city) && (!date || event.date == date)
  });
};
